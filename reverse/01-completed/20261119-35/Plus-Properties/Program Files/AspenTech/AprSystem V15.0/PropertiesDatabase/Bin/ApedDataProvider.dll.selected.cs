	internal abstract class Command
	{
		[NonSerialized]
		private Database myDatabase;

		public Database Database
		{
			get
			{
				return myDatabase;
			}
			set
			{
				myDatabase = value;
			}
		}

		protected Command()
		{
		}

		protected Command(SerializationInfo info, StreamingContext context)
		{
			myDatabase = (Database)context.Context;
		}

		public abstract bool Execute();

		public virtual void GetAuditMessage(out string Message)
		{
			Message = null;
		}

		public static string Serialize(Command command)
		{
			IFormatter formatter = null;
			Stream stream = null;
			StreamReader streamReader = null;
			try
			{
				stream = new MemoryStream();
				formatter = new SoapFormatter();
				formatter.Serialize(stream, command);
				stream.Position = 0L;
				streamReader = new StreamReader(stream);
				return streamReader.ReadToEnd();
			}
			finally
			{
				streamReader?.Close();
				stream?.Close();
			}
		}

		public static Command Deserialize(string data, Database database)
		{
			IFormatter formatter = null;
			Stream stream = null;
			StreamWriter streamWriter = null;
			try
			{
				stream = new MemoryStream(data.Length);
				streamWriter = new StreamWriter(stream, Encoding.Default, data.Length - 1);
				streamWriter.Write(data);
				stream.Position = 0L;
				formatter = new SoapFormatter();
				formatter.Context = new StreamingContext(StreamingContextStates.Persistence, database);
				object obj = formatter.Deserialize(stream);
				return (Command)obj;
			}
			finally
			{
				streamWriter?.Close();
				stream?.Close();
			}
		}
	}
