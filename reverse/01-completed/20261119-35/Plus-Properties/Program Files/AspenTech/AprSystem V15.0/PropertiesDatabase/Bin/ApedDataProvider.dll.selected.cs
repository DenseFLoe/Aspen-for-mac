	internal class ChangeControllerFactory
	{
		public enum ControllerType
		{
			Immediate,
			Reviewed
		}

		public static ChangeController CreateController(Change change)
		{
			Database database = change.Command.Database;
			if (database.ChangeControlManager.IsChangeControlEnabled)
			{
				CommandExecutionModelAttribute commandExecutionModelAttribute = (CommandExecutionModelAttribute)Attribute.GetCustomAttribute(change.Command.GetType(), typeof(CommandExecutionModelAttribute));
				if (commandExecutionModelAttribute.ExecutionModel == CommandExecutionModelType.Reviewed)
				{
					return new ReviewedChangeController(change);
				}
				return new ImmediateChangeController(change);
			}
			return new LocalChangeController(change);
		}
	}
