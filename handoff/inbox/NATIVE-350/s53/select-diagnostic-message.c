/* Windows AMD64 message lookup, zedstwu.dll RVA 0x15000. */
__asm__(
    ".intel_syntax noprefix\n"
    ".text\n"
    ".globl select_diagnostic_message\n"
    ".def select_diagnostic_message; .scl 2; .type 32; .endef\n"
    ".seh_proc select_diagnostic_message\n"
    "select_diagnostic_message:\n"
    "    push rsi\n"
    "    .seh_pushreg rsi\n"
    "    push rdi\n"
    "    .seh_pushreg rdi\n"
    "    sub rsp, 0xc8\n"
    "    .seh_stackalloc 0xc8\n"
    "    .seh_endprologue\n"
    "    mov rax, qword ptr [rip + security_cookie]\n"
    "    xor rax, rsp\n"
    "    mov qword ptr [rsp + 0xc0], rax\n"

    /* Zero selects the statically empty string. Other indexes try the cached module. */
    "    test ecx, ecx\n"
    "    je .Lempty\n"
    "    mov esi, ecx\n"
    "    cmp byte ptr [rip + resource_attempted], 0\n"
    "    jne .Llookup\n"
    "    mov byte ptr [rip + resource_attempted], 1\n"
    "    call qword ptr [rip + imp_get_thread_locale]\n"
    "    lea rdx, [rip + resource_path_format]\n"
    "    lea r9, [rip + resource_dll_name]\n"
    "    lea rdi, [rsp + 0x40]\n"
    "    mov rcx, rdi\n"
    "    mov r8d, eax\n"
    "    call build_resource_path\n"
    "    mov rcx, rdi\n"
    "    xor edx, edx\n"
    "    xor r8d, r8d\n"
    "    call qword ptr [rip + imp_load_library_ex_a]\n"
    "    mov qword ptr [rip + resource_module], rax\n"
    "    test rax, rax\n"
    "    je .Llookup\n"
    "    mov byte ptr [rip + resource_available], 1\n"

    /* Each fallback record is 16 bytes and holds its message address at +8. */
    ".Llookup:\n"
    "    movsxd rax, esi\n"
    "    shl rax, 4\n"
    "    lea rcx, [rip + fallback_records]\n"
    "    mov rdi, qword ptr [rax + rcx + 8]\n"
    "    cmp byte ptr [rip + resource_available], 1\n"
    "    jne .Lreturn\n"
    "    add esi, 0x80000000\n"
    "    mov rdx, qword ptr [rip + resource_module]\n"
    "    lea rax, [rsp + 0x40]\n"
    "    mov qword ptr [rsp + 0x20], rax\n"
    "    mov qword ptr [rsp + 0x30], 0\n"
    "    mov dword ptr [rsp + 0x28], 0x200\n"
    "    mov ecx, 0x900\n"
    "    mov r8d, esi\n"
    "    mov r9d, 0x409\n"
    "    call qword ptr [rip + imp_format_message_a]\n"
    "    test eax, eax\n"
    "    je .Lreturn\n"

    /* Trim a terminal CR/LF pair. Otherwise use the fixed buffer capacity. */
    "    mov rsi, qword ptr [rsp + 0x40]\n"
    "    mov rcx, rsi\n"
    "    call strlen_thunk\n"
    "    cmp rax, 2\n"
    "    jb .Lbounded_copy\n"
    "    cmp byte ptr [rsi + rax - 2], 0xd\n"
    "    jne .Lbounded_copy\n"
    "    cmp byte ptr [rax + rsi - 1], 0xa\n"
    "    jne .Lbounded_copy\n"
    "    add rax, -2\n"
    "    lea rdi, [rip + localized_message]\n"
    "    mov rcx, rdi\n"
    "    mov rdx, rsi\n"
    "    mov r8, rax\n"
    "    mov rsi, rax\n"
    "    call strncpy_thunk\n"
    "    mov rax, rsi\n"
    "    add rax, rdi\n"
    "    jmp .Lterminate\n"
    ".Lempty:\n"
    "    lea rdi, [rip + empty_message]\n"
    "    jmp .Lreturn\n"
    ".Lbounded_copy:\n"
    "    lea rcx, [rip + localized_message]\n"
    "    mov r8d, 0x200\n"
    "    mov rdx, rsi\n"
    "    call strncpy_thunk\n"
    "    lea rax, [rip + localized_message_last]\n"
    ".Lterminate:\n"
    "    mov byte ptr [rax], 0\n"
    "    mov rcx, qword ptr [rsp + 0x40]\n"
    "    call qword ptr [rip + imp_local_free]\n"
    "    lea rdi, [rip + localized_message]\n"
    ".Lreturn:\n"
    "    mov rcx, qword ptr [rsp + 0xc0]\n"
    "    xor rcx, rsp\n"
    "    call check_security_cookie\n"
    "    mov rax, rdi\n"
    "    add rsp, 0xc8\n"
    "    pop rdi\n"
    "    pop rsi\n"
    "    ret\n"
    "select_diagnostic_message_end:\n"
    ".seh_endproc\n"
);
