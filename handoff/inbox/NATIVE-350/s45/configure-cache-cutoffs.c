/* zedstwu.dll, Windows AMD64. Addresses in symbol names are original RVAs. */
__asm__(
    ".intel_syntax noprefix\n"
    ".text\n"
    ".globl configure_cache_cutoffs\n"
    ".def configure_cache_cutoffs; .scl 2; .type 32; .endef\n"
    ".seh_proc configure_cache_cutoffs\n"
    "configure_cache_cutoffs:\n"
    "    push rbp\n"
    "    .seh_pushreg rbp\n"
    "    push rsi\n"
    "    .seh_pushreg rsi\n"
    "    push rbx\n"
    "    .seh_pushreg rbx\n"
    "    sub rsp, 0x50\n"
    "    .seh_stackalloc 0x50\n"
    "    lea rbp, [rsp + 0x50]\n"
    "    .seh_setframe rbp, 0x50\n"
    "    .seh_endprologue\n"
    "    mov rax, qword ptr [rip + security_cookie]\n"
    "    xor rax, rbp\n"
    "    mov qword ptr [rbp - 8], rax\n"

    /* Read the 32-bit ready flag, and initialize only on zero. */
    "    cmp dword ptr [rip + cache_ready], 0\n"
    "    jne .Lread_vendor\n"
    "    call initialize_capability_records\n"

    /* Intel metadata controls the basic CPUID path. */
    ".Lread_vendor:\n"
    "    cmp dword ptr [rip + intel_vendor_match], 0\n"
    "    je .Lprobe_amd\n"
    "    cmp dword ptr [rip + max_basic_leaf], 0\n"
    "    je .Lno_basic_leaf\n"
    "    push rbx\n"
    "    mov eax, 1\n"
    "    cpuid\n"
    "    mov dword ptr [rbp - 0x20], ebx\n"
    "    mov dword ptr [rbp - 0x28], edx\n"
    "    mov dword ptr [rbp - 0x2c], eax\n"
    "    pop rbx\n"
    "    mov eax, dword ptr [rbp - 0x28]\n"
    "    mov ecx, eax\n"
    "    shr ecx, 0x17\n"
    "    and ecx, 1\n"
    "    bt eax, 0x1a\n"
    "    mov esi, 2\n"
    "    cmovae esi, ecx\n"
    "    jmp .Lselect_cache\n"

    /* Match AuthenticAMD in EBX, EDX, ECX order. */
    ".Lprobe_amd:\n"
    "    lea r9, [rbp - 0x20]\n"
    "    mov qword ptr [rbp - 0x28], r9\n"
    "    mov dword ptr [rbp - 0x2c], 0\n"
    "    push rax\n"
    "    push rbx\n"
    "    push rcx\n"
    "    push rdx\n"
    "    mov r8, qword ptr [rbp - 0x28]\n"
    "    mov eax, dword ptr [rbp - 0x2c]\n"
    "    cpuid\n"
    "    mov dword ptr [r8], eax\n"
    "    mov dword ptr [r8 + 4], ebx\n"
    "    mov dword ptr [r8 + 8], ecx\n"
    "    mov dword ptr [r8 + 0xc], edx\n"
    "    pop rdx\n"
    "    pop rcx\n"
    "    pop rbx\n"
    "    pop rax\n"
    "    xor esi, esi\n"
    "    cmp dword ptr [r9 + 4], 0x68747541\n"
    "    jne .Lpublish_feature_class\n"
    "    cmp dword ptr [rbp - 0x14], 0x69746e65\n"
    "    jne .Lpublish_feature_class\n"
    "    cmp dword ptr [rbp - 0x18], 0x444d4163\n"
    "    jne .Lpublish_feature_class\n"
    "    mov qword ptr [rbp - 0x28], r9\n"
    "    mov dword ptr [rbp - 0x2c], 1\n"
    "    push rax\n"
    "    push rbx\n"
    "    push rcx\n"
    "    push rdx\n"
    "    mov r8, qword ptr [rbp - 0x28]\n"
    "    mov eax, dword ptr [rbp - 0x2c]\n"
    "    cpuid\n"
    "    mov dword ptr [r8], eax\n"
    "    mov dword ptr [r8 + 4], ebx\n"
    "    mov dword ptr [r8 + 8], ecx\n"
    "    mov dword ptr [r8 + 0xc], edx\n"
    "    pop rdx\n"
    "    pop rcx\n"
    "    pop rbx\n"
    "    pop rax\n"
    "    mov esi, dword ptr [rbp - 0x14]\n"
    "    shr esi, 0x17\n"
    "    and esi, 1\n"

    /* Read the maximum extended leaf before querying 0x80000006. */
    "    mov qword ptr [rbp - 0x28], r9\n"
    "    mov dword ptr [rbp - 0x2c], 0x80000000\n"
    "    push rax\n"
    "    push rbx\n"
    "    push rcx\n"
    "    push rdx\n"
    "    mov r8, qword ptr [rbp - 0x28]\n"
    "    mov eax, dword ptr [rbp - 0x2c]\n"
    "    cpuid\n"
    "    mov dword ptr [r8], eax\n"
    "    mov dword ptr [r8 + 4], ebx\n"
    "    mov dword ptr [r8 + 8], ecx\n"
    "    mov dword ptr [r8 + 0xc], edx\n"
    "    pop rdx\n"
    "    pop rcx\n"
    "    pop rbx\n"
    "    pop rax\n"
    "    cmp dword ptr [rbp - 0x20], 0x80000006\n"
    "    jb .Lpublish_feature_class\n"
    "    mov qword ptr [rbp - 0x28], r9\n"
    "    mov dword ptr [rbp - 0x2c], 0x80000006\n"
    "    push rax\n"
    "    push rbx\n"
    "    push rcx\n"
    "    push rdx\n"
    "    mov r8, qword ptr [rbp - 0x28]\n"
    "    mov eax, dword ptr [rbp - 0x2c]\n"
    "    cpuid\n"
    "    mov dword ptr [r8], eax\n"
    "    mov dword ptr [r8 + 4], ebx\n"
    "    mov dword ptr [r8 + 8], ecx\n"
    "    mov dword ptr [r8 + 0xc], edx\n"
    "    pop rdx\n"
    "    pop rcx\n"
    "    pop rbx\n"
    "    pop rax\n"

    /* AMD leaf 0x80000006 ECX[31:16] supplies the capacity in KiB. */
    "    movzx eax, word ptr [rbp - 0x16]\n"
    "    shl eax, 0xa\n"
    "    mov qword ptr [rip + cutoff_22230], rax\n"
    "    shr eax, 1\n"
    "    mov qword ptr [rip + cutoff_22238], rax\n"
    "    mov rax, qword ptr [rip + cutoff_22240]\n"
    "    shr rax, 2\n"
    "    mov qword ptr [rip + cutoff_22250], rax\n"
    "    jmp .Lpublish_feature_class\n"
    ".Lno_basic_leaf:\n"
    "    xor esi, esi\n"

    /* First-level capacity zero diverts to the environment check. */
    ".Lselect_cache:\n"
    "    mov eax, dword ptr [rip + cache1_capacity]\n"
    "    test eax, eax\n"
    "    je .Lcheck_debug_variable\n"
    "    mov ecx, dword ptr [rip + cache2_field8]\n"
    "    imul ecx, dword ptr [rip + cache2_field4]\n"
    "    mov edx, dword ptr [rip + cache2_capacity]\n"
    "    mov r8d, dword ptr [rip + cache1_field8]\n"
    "    imul r8d, dword ptr [rip + cache1_field4]\n"

    /* Unsigned comparisons select the larger capacity; ties keep the earlier product. */
    "    cmp eax, edx\n"
    "    cmova edx, eax\n"
    "    cmovb r8d, ecx\n"
    "    mov ecx, dword ptr [rip + cache3_field8]\n"
    "    imul ecx, dword ptr [rip + cache3_field4]\n"
    "    mov r9d, dword ptr [rip + cache3_capacity]\n"
    "    cmp edx, r9d\n"
    "    cmovae ecx, r8d\n"
    "    cmovbe edx, r9d\n"

    /* The maximum capacity scales in 64 bits. The first capacity scales in 32 bits. */
    "    mov r8, rdx\n"
    "    shl r8, 0xa\n"
    "    mov qword ptr [rip + cutoff_22230], r8\n"
    "    shl rdx, 9\n"
    "    mov qword ptr [rip + cutoff_22238], rdx\n"
    "    shl eax, 0xa\n"
    "    mov qword ptr [rip + cutoff_22240], rax\n"
    "    mov edx, eax\n"
    "    shr edx, 1\n"
    "    mov qword ptr [rip + cutoff_22248], rdx\n"
    "    mov edx, eax\n"
    "    shr edx, 2\n"
    "    mov qword ptr [rip + cutoff_22250], rdx\n"
    "    mov qword ptr [rip + selected_product], rcx\n"
    "    mov qword ptr [rip + cutoff_22258], 0x2000\n"
    "    add rax, rax\n"
    "    lea rax, [rax + rax*2]\n"
    "    mov qword ptr [rip + cutoff_22260], rax\n"
    "    mov qword ptr [rip + cutoff_22268], 0x800\n"
    "    jmp .Lpublish_feature_class\n"

    /* The environment string is used only after a zero first capacity. */
    ".Lcheck_debug_variable:\n"
    "    lea rcx, [rip + debug_variable_name]\n"
    "    call getenv_thunk\n"
    "    test rax, rax\n"
    "    je .Lpublish_feature_class\n"
    "    cmp byte ptr [rax], 0\n"
    "    jne .Lreport_then_exit\n"

    /* Publish both classification dwords, check the cookie, and return. */
    ".Lpublish_feature_class:\n"
    "    mov dword ptr [rip + feature_class_a], esi\n"
    "    mov dword ptr [rip + feature_class_b], esi\n"
    "    mov rcx, qword ptr [rbp - 8]\n"
    "    xor rcx, rbp\n"
    "    call check_security_cookie\n"
    "    nop\n"
    "    add rsp, 0x50\n"
    "    pop rbx\n"
    "    pop rsi\n"
    "    pop rbp\n"
    "    ret\n"

    /* Three calls to the same reporting helper precede exit(1). */
    ".Lreport_then_exit:\n"
    "    mov ecx, 1\n"
    "    xor edx, edx\n"
    "    xor r8d, r8d\n"
    "    call report_helper\n"
    "    mov ecx, 1\n"
    "    mov edx, 0x3d\n"
    "    xor r8d, r8d\n"
    "    call report_helper\n"
    "    mov ecx, 1\n"
    "    xor edx, edx\n"
    "    xor r8d, r8d\n"
    "    call report_helper\n"
    "    mov ecx, 1\n"
    "    call exit_thunk\n"
    "    int3\n"
    "configure_cache_cutoffs_end:\n"
    ".seh_endproc\n"
    ".att_syntax prefix\n"
);
