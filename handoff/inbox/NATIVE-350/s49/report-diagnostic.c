/* Windows AMD64 diagnostic helper, zedstwu.dll RVA 0x15180. */
__asm__(
    ".intel_syntax noprefix\n"
    ".text\n"
    ".globl report_diagnostic\n"
    ".def report_diagnostic; .scl 2; .type 32; .endef\n"
    ".seh_proc report_diagnostic\n"
    "report_diagnostic:\n"
    "    push rsi\n"
    "    .seh_pushreg rsi\n"
    "    push rdi\n"
    "    .seh_pushreg rdi\n"
    "    sub rsp, 0x48\n"
    "    .seh_stackalloc 0x48\n"
    "    .seh_endprologue\n"
    "    mov qword ptr [rsp + 0x78], r9\n"
    "    mov rax, qword ptr [rip + security_cookie]\n"
    "    xor rax, rsp\n"
    "    mov qword ptr [rsp + 0x40], rax\n"

    /* EDX selects newline or message. R8D gates varargs formatting. */
    "    test edx, edx\n"
    "    je .Lnewline\n"
    "    mov edi, r8d\n"
    "    mov ecx, edx\n"
    "    call message_for_index\n"
    "    mov rsi, rax\n"
    "    test edi, edi\n"
    "    jle .Lprint_message\n"

    /* The va_list starts in the saved R9 home slot. */
    "    lea rdi, [rsp + 0x78]\n"
    "    mov qword ptr [rsp + 0x38], rdi\n"
    "    call stdio_options_address\n"
    "    mov rcx, qword ptr [rax]\n"
    "    or rcx, 2\n"
    "    mov qword ptr [rsp + 0x28], rdi\n"
    "    mov qword ptr [rsp + 0x20], 0\n"
    "    lea rdi, [rip + diagnostic_buffer]\n"
    "    mov r8d, 0x200\n"
    "    mov rdx, rdi\n"
    "    mov r9, rsi\n"
    "    call common_vsprintf_thunk\n"
    "    mov rsi, rdi\n"

    ".Lprint_message:\n"
    "    lea rcx, [rip + message_format]\n"
    "    mov rdx, rsi\n"
    "    call write_diagnostic\n"
    "    jmp .Lcheck_cookie\n"
    ".Lnewline:\n"
    "    lea rcx, [rip + newline_format]\n"
    "    call write_diagnostic\n"
    ".Lcheck_cookie:\n"
    "    mov rcx, qword ptr [rsp + 0x40]\n"
    "    xor rcx, rsp\n"
    "    call check_security_cookie\n"
    "    nop\n"
    "    add rsp, 0x48\n"
    "    pop rdi\n"
    "    pop rsi\n"
    "    ret\n"
    "report_diagnostic_end:\n"
    ".seh_endproc\n"
);
